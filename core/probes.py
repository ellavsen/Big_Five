"""Банк житейских ситуаций, из которых виден человек.

Зачем это отдельным слоем. Планировщик, оставленный наедине с задачей «спроси
что-нибудь ещё», отзеркаливает тему собеседника: в живом прогоне человек говорил
про усталость — и получил семь вопросов подряд про восстановление, пять
наблюдений по одной черте и ноль по остальным четырём.

Выбор темы — это арифметика «где меньше всего собрано», а не творчество. Поэтому
тема выбирается кодом (`core/coverage.py`), а модели остаётся живая формулировка.

Два правила банка, оба выведены из ошибок:

1. **Никаких вариантов ответа.** «Большая компания или три человека?» — это тест
   с вариантами: человек выбирает ярлык вместо рассказа, а два полюса в вопросе
   прямо называют измеряемое. Спрашиваем открыто, отвечает человек своими словами.
   Держится тестом `test_probes_offer_no_answer_options`.

2. **Вопрос не выдаёт, что измеряет.** «Как ты справляешься со стрессом» — плохо.
   «Когда последний раз рушились планы» — хорошо: рассказ про случай даёт эпизод,
   а эпизод весит вдвое против самоописания (см. `direct_example` в CLAUDE.md).

Про род: русское прошедшее время его выдаёт («пробовал» / «пробовала»), а пола
собеседника система не знает. Формулировки подобраны так, чтобы род не требовался.
"""
from __future__ import annotations

from dataclasses import dataclass

from core.models import Trait


@dataclass(frozen=True)
class Probe:
    """Одна ситуация.

    `question` — опорная формулировка: модель вплетает её в разговор своими
    словами, но саму ситуацию менять не может.
    `traits` — что обычно проявляется в ответе. Подсказка для выбора, а не
    ограничение: наблюдения фиксируются по всему сказанному.
    """

    id: str
    question: str
    traits: tuple[Trait, ...]


# Короткие имена — чтобы таблица ситуаций читалась как таблица.
# Не `O`: ruff справедливо путает заглавную O с нулём.
OPEN = Trait.OPENNESS
CONS = Trait.CONSCIENTIOUSNESS
EXTR = Trait.EXTRAVERSION
AGRE = Trait.AGREEABLENESS
NEUR = Trait.NEUROTICISM


