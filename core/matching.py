"""Поиск маркеров в русском тексте с учётом отрицаний.

Модули матчат по основам слов («контрол», «устал») — это бедный стеммер, который
покрывает большую часть словоформ. Чего он не умел совсем — видеть отрицание:
«не контролирую» давало ровно тот же сигнал, что и «контролирую».

Полноценная лемматизация (pymorphy3) осознанно отложена, см. docs/ROADMAP.md.
"""
from __future__ import annotations

import re
from typing import Iterable

# Слова, которые переворачивают смысл следующего за ними маркера.
NEGATIONS = {
    "не", "ни", "нет", "без",
    "никогда", "никак", "ничего", "нисколько",
    "редко", "перестала", "перестал", "разучилась", "разучился",
}

# Сколько слов перед маркером просматриваем в поисках отрицания.
# Три — компромисс: ловит «я совсем ничего не контролирую», но на «не только
# контролирую, но и делегирую» ошибётся в сторону осторожности.
NEGATION_WINDOW = 3

# Признаки конкретного эпизода. Только при них сигнал считается прямым примером:
# «я контролирую» — самоописание, «вчера я всё контролировала» — наблюдаемый случай.
EPISODE_MARKERS = [
    "вчера",
    "сегодня",
    "позавчера",
    "на прошлой неделе",
    "недавно",
    "однажды",
    "в тот момент",
    "в какой-то момент",
    "в прошлый раз",
]

_WORDS = re.compile(r"\w+", re.UNICODE)


def _is_negated(lowered: str, marker_start: int) -> bool:
    preceding = _WORDS.findall(lowered[:marker_start])[-NEGATION_WINDOW:]
    return any(word in NEGATIONS for word in preceding)


def find_marker(text: str, markers: Iterable[str]) -> str | None:
    """
    Первый маркер, встретившийся в тексте БЕЗ отрицания перед ним. Иначе None.

    Один и тот же маркер может встретиться дважды («не контролирую, но всё же
    контролирую всё»), поэтому проверяем все вхождения, а не только первое.
    """
    lowered = (text or "").lower()

    for marker in markers:
        start = 0
        while (found := lowered.find(marker, start)) != -1:
            if not _is_negated(lowered, found):
                return marker
            start = found + 1

    return None


def has_episode(text: str) -> bool:
    """Есть ли в тексте признак конкретного случая, а не общего самоописания."""
    return find_marker(text, EPISODE_MARKERS) is not None
